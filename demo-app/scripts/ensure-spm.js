#!/usr/bin/env node
/**
 * Ensures React Native's generated Swift Package Manager packages exist before
 * any `xcodebuild` invocation (run-ios, Detox, bare xcodebuild).
 *
 * Why this exists: since migrating the iOS app from CocoaPods to SwiftPM, the
 * Xcode project references three *generated* local SPM packages:
 *
 *   ios/build/generated/ios          (React-GeneratedCode — codegen output)
 *   ios/build/xcframeworks           (ReactNative — prebuilt React xcframeworks)
 *   ios/build/generated/autolinking  (Autolinked — native module autolinking)
 *
 * These live under `ios/build/`, which is git-ignored and wiped by any clean.
 * They are normally regenerated by the "Sync SPM Autolinking" build phase, but
 * `react-native run-ios` (and Detox) run `xcodebuild -list` *first* to discover
 * schemes — and SwiftPM package resolution fails before any build phase runs if
 * those package directories are missing:
 *
 *   xcodebuild: error: Could not resolve package dependencies:
 *     the package at '.../ios/build/generated/ios' cannot be accessed ...
 *
 * So we regenerate them here (idempotent, and a no-op/fast when already present)
 * via `react-native spm update`.
 */
const fs = require('fs');
const path = require('path');
const {spawnSync} = require('child_process');

const appRoot = path.join(__dirname, '..');
const requiredDirs = [
  'ios/build/generated/ios',
  'ios/build/xcframeworks',
  'ios/build/generated/autolinking',
];

const missing = requiredDirs.filter(
  (d) => !fs.existsSync(path.join(appRoot, d)),
);

if (missing.length === 0) {
  process.exit(0);
}

console.log(
  `[ensure-spm] Generated SPM packages missing (${missing.join(
    ', ',
  )}); regenerating via "react-native spm update"...`,
);

const result = spawnSync(
  'npx',
  ['react-native', 'spm', 'update', '--yes'],
  {cwd: appRoot, stdio: 'inherit'},
);

if (result.status !== 0) {
  console.error(
    '[ensure-spm] Failed to regenerate SPM packages. Run ' +
      '"npx react-native spm update" manually and check the output above.',
  );
  process.exit(result.status ?? 1);
}
